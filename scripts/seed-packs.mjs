#!/usr/bin/env node
// Repeatable course-pack seed.
//
// Writes the resolved packs to supabase/seed/10-course-packs.json so the local
// Supabase reset (supabase/config.toml -> db.seed) can import them, and hosts
// can push the same content through POST /api/packs/import (see
// src/server/api/packs.js). The database trigger rebuilds normalized rows from
// the pack document with the service role; students can never write content.
//
// Usage: npm run seed:packs   (add --check to fail when the file is stale)
import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { pathToFileURL } from "node:url";
import { PACKS, validatePack } from "../src/content/packs/index.js";

export function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object")
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`)
      .join(",")}}`;
  return JSON.stringify(value);
}

export function resolvePacks(packs = PACKS) {
  const resolved = [];
  for (const pack of packs) {
    const errors = validatePack(pack);
    if (errors.length)
      throw new Error(`Invalid course pack ${pack?.id}: ${errors.join("; ")}`);
    const contentHash = crypto
      .createHash("sha256")
      .update(stableStringify(pack))
      .digest("hex");
    resolved.push({ contentHash, pack });
  }
  return resolved;
}

export const SEED_PATH = path.resolve(
  import.meta.dirname,
  "../supabase/seed/10-course-packs.json",
);

async function main() {
  const check = process.argv.includes("--check");
  const resolved = resolvePacks();
  const document = {
    note: "Generated by npm run seed:packs. Do not edit by hand.",
    packs: resolved.map(({ contentHash, pack }) => ({
      contentHash,
      publicationStatus: pack.publicationStatus,
      pack,
    })),
  };
  const body = JSON.stringify(document, null, 2) + "\n";
  let previous = null;
  try {
    previous = await fs.readFile(SEED_PATH, "utf8");
  } catch { }
  if (check) {
    if (previous !== body) {
      console.error("supabase/seed/10-course-packs.json is stale. Run npm run seed:packs.");
      process.exitCode = 1;
    } else console.log("Course pack seed is up to date.");
    return;
  }
  await fs.mkdir(path.dirname(SEED_PATH), { recursive: true });
  await fs.writeFile(SEED_PATH, body);
  for (const { contentHash, pack } of resolved)
    console.log(
      `Seeded ${pack.id}@${pack.version} (${pack.counts.topics} topics, ${pack.counts.quiz} MCQs) hash ${contentHash.slice(0, 12)}`,
    );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
)
  await main();
